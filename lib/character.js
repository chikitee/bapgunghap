// 받침이 있으면 '이에요', 없으면 '예요'
const copula = (word) => ((word.charCodeAt(word.length - 1) - 0xac00) % 28 ? '이에요' : '예요');

/**
 * @param {{pillars: {day: string}}} saju computeSaju 결과
 */
export function readCharacter(saju) {
  const [stem, branch] = saju.pillars.day;
  const color = COLOR_OF_STEM[stem];
  const [animal, emoji, animalText] = ANIMAL[branch];
  return {
    title: `${color} ${animal}`,
    emoji,
    body: `${COLOR_VIBE[color]} ${animal}${copula(animal)}. ${animalText}`,
  };
}
